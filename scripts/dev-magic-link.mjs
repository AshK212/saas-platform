#!/usr/bin/env node
/**
 * Prints a magic-link sign-in URL locally, instead of emailing it.
 *
 * ─── WHY THIS EXISTS ──────────────────────────────────────────────────────
 *
 * Authentication gates every other Credit surface: no session means no
 * workspace, no API key, no agents, no policy, no governance view. So an email
 * that cannot be delivered blocks all local testing, not just sign-in.
 *
 * Right now delivery is impossible for anyone but the Resend account owner:
 * the sender is `onboarding@resend.dev`, Resend's sandbox address, which only
 * delivers to the address that owns the account. That is a DNS problem waiting
 * on `huelabs.ai` verification, and nothing a developer can fix locally.
 *
 * ─── WHAT THIS DOES, AND DOES NOT, CHANGE ─────────────────────────────────
 *
 * It runs the REAL `createAuthService` against the REAL Drizzle store. The user
 * is created the same way, the token is generated by the same CSPRNG, hashed
 * with the same SHA-256, and written to the same `auth_magic_links` row with
 * the same 15-minute expiry.
 *
 * The ONLY substitution is the mailer: `createCapturingEmailSender` - already
 * in the codebase, already used by the auth test suite - captures the message
 * in memory instead of calling Resend. So the URL printed below is the exact
 * URL the email would have contained, and redeeming it exercises the real
 * callback, the real single-use consumption and the real session cookie.
 *
 * Nothing about the deployed application changes. There is no new route, no
 * new authentication path, and no way to reach this from HTTP.
 *
 * ─── WHY IT IS NOT A BACK DOOR ────────────────────────────────────────────
 *
 * It requires DATABASE_URL. Anyone holding that already has unrestricted read
 * and write access to every table, including the ability to insert a session
 * row directly. This grants no capability that credential did not already
 * carry - it just saves an hour of doing it by hand.
 *
 * It nonetheless refuses to run under NODE_ENV=production, because "no new
 * capability" is a bad reason to leave a sharp edge lying around.
 *
 * Usage:
 *   node --env-file=.env scripts/dev-magic-link.mjs you@example.com
 */

import { createRequire } from 'node:module';
import path from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';

const email = process.argv[2];
if (email === undefined || !email.includes('@')) {
  console.error('usage: node --env-file=.env scripts/dev-magic-link.mjs <email>');
  process.exit(2);
}

if ((process.env['NODE_ENV'] ?? '').trim() === 'production') {
  console.error('[dev-magic-link] REFUSED: NODE_ENV=production.');
  console.error('  This is a local development aid. In a deployed environment the');
  console.error('  magic link must travel by email, so that possession of an inbox');
  console.error('  remains the thing being proven.');
  process.exit(1);
}

const databaseUrl = (process.env['DATABASE_URL'] ?? '').trim();
if (databaseUrl === '') {
  console.error('[dev-magic-link] DATABASE_URL is not set. Pass --env-file=.env.');
  process.exit(1);
}

const appUrl = (process.env['APP_URL'] ?? 'http://localhost:5173').trim();

// Imported from the BUILT api, so this cannot drift from what runs in
// production - if the build is stale, this fails rather than lying.
const dist = (...segments) =>
  pathToFileURL(path.resolve('apps', 'api', 'dist', ...segments)).href;

const { createAuthService } = await import(dist('auth', 'service.js'));
const { createDrizzleAuthStore } = await import(dist('auth', 'store.js'));
const { createCapturingEmailSender } = await import(dist('auth', 'email.js'));
const { systemClock } = await import(dist('auth', 'clock.js'));

const require = createRequire(import.meta.url);
const dbEntry = require.resolve('@hybrid/db', { paths: [path.resolve('apps', 'api')] });
const { createDatabasePool, createDatabaseClient, closeDatabasePool } = await import(
  pathToFileURL(dbEntry).href
);

const { AUTH_CALLBACK_PATH } = await import(
  pathToFileURL(
    require.resolve('@hybrid/contracts', { paths: [path.resolve('apps', 'api')] }),
  ).href
);

const pool = createDatabasePool({
  connectionString: databaseUrl,
  maxConnections: 1,
  applicationName: 'hybrid-dev-magic-link',
});

try {
  const mailer = createCapturingEmailSender();
  const service = createAuthService({
    store: createDrizzleAuthStore(createDatabaseClient(pool)),
    mailer,
    clock: systemClock,
    appUrl,
    callbackPath: AUTH_CALLBACK_PATH,
  });

  await service.requestMagicLink(email);

  const captured = mailer.lastLink();
  if (captured === undefined || captured === null) {
    // The service applies a 60-second per-address cooldown and returns quietly
    // when it trips, so silence here is expected rather than broken.
    console.error('[dev-magic-link] No link was issued.');
    console.error('  Most likely the 60-second cooldown for this address is still');
    console.error('  running. Wait a moment and try again.');
    process.exit(1);
  }

  console.log('');
  console.log('  Sign-in link for ' + email + ':');
  console.log('');
  console.log('  ' + captured.url);
  console.log('');
  console.log('  Single use, expires in 15 minutes. Paste it into your browser.');
  console.log('');
} finally {
  await closeDatabasePool(pool);
}
